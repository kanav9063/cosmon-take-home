#!/usr/bin/env python3
"""Run offline regression tests and validate all checked-in example reports."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import platform
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from eval_types import canonical, digest
from evaluate import evaluate_batch

DIMENSIONS = ("capture_integrity", "process_compliance", "final_correctness",
              "delivery", "reporting_accuracy", "repair_achievement")
# These expectations are test oracles. The evaluator never reads this table.
EXPECTED = {
    "already_safe": ("PPPPPN", None),
    "guard_blocked": ("PPPPPP", None),
    "historical_artifact": ("PPPPPP", None),
    "honest_exhaustion": ("PPNNPF", None),
    "illegal_restored": ("PFPPPP", "MANUFACTURING_VIOLATION"),
    "missing_artifact": ("UUUUUU", "ARTIFACT_MISSING"),
    "missing_result": ("UUPUUU", "CALL_RESULT_MISSING"),
    "multi_parameter": ("PFFPFF", "SINGLE_PARAMETER_VIOLATION"),
    "overwritten_publication": ("PPPFFF", "FINAL_OUTPUT_MISMATCH"),
    "partial_tail": ("UUPUUU", "TRACE_INCOMPLETE"),
    "recovered_cli": ("PPPPPP", None),
    "repaired": ("PPPPPP", None),
    "scripted_bracket_v3": ("PPPPPP", None),
    "scripted_flange_v1": ("PPNNPF", None),
    "stale_solve": ("PPFPFF", "STALE_SOLVE"),
    "wrong_load": ("PPFPFF", "DEFAULT_LOAD_MISMATCH"),
    "live_bracket_v3": ("PPPPPP", None),
    "live_flange_v1": ("PPNNPF", None),
    "producer_guard": ("PPNNPF", None),
}
STATUS = {"P": "pass", "F": "fail", "U": "unknown", "N": "not_applicable"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True, type=Path,
                        help="New destination for checked reports and verification record")
    args = parser.parse_args()
    if args.output_dir.exists():
        parser.error("Choose a new output directory")
    suite = unittest.defaultTestLoader.discover(str(ROOT / "tests"))
    result = unittest.TextTestRunner(verbosity=1).run(suite)
    if not result.wasSuccessful():
        return 1
    summary = evaluate_batch(ROOT / "fixtures/all-inputs.json", args.output_dir)
    assert (summary["requested"], summary["evaluated"], summary["explicitly_rejected"]) == (19, 19, 0)
    observed = {}
    rows = ["# Checked example reports", "", "Generated by `python3 scripts/verify.py`. "
            "All rows are asserted against independent test expectations. "
            "Fourteen bundles are synthetic; three are scripted captures; two are existing live "
            "agent captures copied unchanged from the producer. This verification makes no model calls.", "",
            "| Example | Capture | Process | Final | Delivery | Reporting | Repair |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for name, (expected, required_code) in EXPECTED.items():
        report = json.loads((args.output_dir / f"report-{name}.json").read_bytes())
        actual = [report["summary"][key]["status"] for key in DIMENSIONS]
        assert actual == [STATUS[item] for item in expected], (name, actual)
        codes = {item["code"] for item in report["findings"]}
        assert required_code is None or required_code in codes, (name, codes)
        if name in {"repaired", "guard_blocked", "recovered_cli", "historical_artifact", "already_safe", "scripted_bracket_v3", "live_bracket_v3"}:
            assert not report["findings"], (name, report["findings"])
        if name in {"guard_blocked", "recovered_cli"}:
            assert report["diagnostics"], name
        if name == "stale_solve":
            stale = next(item for item in report["findings"] if item["code"] == "STALE_SOLVE")
            assert stale["status"] == "fail" and len(stale["refs"]) >= 3
            assert not codes.intersection({"MANUFACTURING_VIOLATION", "SINGLE_PARAMETER_VIOLATION"})
        origin = ("live_agent" if name.startswith("live_") else "preparation_check"
                  if name.startswith("scripted_") or name == "producer_guard" else "synthetic_fixture")
        assert report["source_kind"] == origin
        observed[name] = dict(zip(DIMENSIONS, actual))
        rows.append(f"| [{name}](report-{name}.json) | " + " | ".join(actual) + " |")
    files = ["eval_types.py", "trace_adapter.py", "eval_state.py", "eval_checks.py", "evaluate.py", "eval_cases.json"]
    verification = {"status": "pass", "python": platform.python_version(),
                    "tests_run": result.testsRun, "failures": len(result.failures), "errors": len(result.errors),
                    "example_bundles": len(EXPECTED), "live_model_runs": 2,
                    "model_calls_during_verification": 0,
                    "source_sha256": {name: digest((ROOT / name).read_bytes()) for name in files},
                    "checked_dimensions": observed}
    (args.output_dir / "verification.json").write_bytes(canonical(verification))
    (args.output_dir / "REPORTS.md").write_text("\n".join(rows) + "\n")
    print(json.dumps({key: verification[key] for key in ("status", "tests_run", "example_bundles", "live_model_runs")}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
